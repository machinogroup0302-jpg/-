const DAY = 86400000;

// 記事の数の増え方：直近2日の1日あたりの数 ÷ その前5日の1日あたりの数
export function themeHeat(items, now = Date.now()) {
  let recent = 0, before = 0;
  for (const it of items) {
    const t = Date.parse(it.date);
    if (!Number.isFinite(t)) continue;
    const age = now - t;
    if (age < 2 * DAY) recent++;
    else if (age < 7 * DAY) before++;
  }
  const heat = (recent / 2) / Math.max(0.5, before / 5);
  const label = recent >= 10 && heat >= 1.8 ? '急に増えている' : recent >= 10 && heat >= 1.2 ? '増えている' : recent >= 20 ? 'たくさん出ている' : recent >= 4 ? 'ふつう' : '少ない';
  return { recent, before, heat: Math.round(heat * 10) / 10, label };
}

let cache = null;

export async function getThemes() {
  if (cache && Date.now() - cache.at < 30 * 60 * 1000) return cache.data;
  const now = Date.now();
  const themes = await Promise.all(THEMES.map(async (t) => {
    let items = [];
    try {
      items = await fetchRss(`https://news.google.com/rss/search?q=${encodeURIComponent(`${t.q} when:7d`)}&hl=ja&gl=JP&ceid=JP:ja`);
    } catch { /* 取れなかったテーマは0件 */ }
    const seen = new Set();
    items = items.filter((it) => (seen.has(it.title) ? false : seen.add(it.title)));
    const kept = scoreItems(items).filter((x) => x.verdict !== '除外');
    const h = themeHeat(kept, now);
    const headlines = kept.sort((a, b) => Date.parse(b.date) - Date.parse(a.date)).slice(0, 4)
      .map(({ title, source, url, date }) => ({ title, source, url, date }));
    // 並べる順番：最近の記事が多くて、増え方も大きいものほど上
    const score = h.recent * Math.min(3, Math.max(0.5, h.heat));
    return { id: t.id, dir: t.dir || 1, name: t.name, why: t.why, stock: t.stock, us: t.us, ...h, score, headlines };
  }));
  themes.sort((a, b) => b.score - a.score);
  const data = { at: now, themes };
  if (themes.some((t) => t.recent + t.before > 0)) cache = { at: now, data };
  return data;
}
