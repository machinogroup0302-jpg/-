const BY_SYMBOL = new Map(US_STOCKS.map((x) => [x.symbol, x]));

export function usName(symbol) {
  return BY_SYMBOL.get(String(symbol || '').toUpperCase())?.name || null;
}

const norm = (s) => String(s || '').normalize('NFKC').toLowerCase().replace(/[\s・（）()]/g, '');
// カタカナとひらがなを同じものとして探す
const kata = (s) => s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));

export function searchUs(q, limit = 20) {
  const n = kata(norm(q));
  if (!n) return [];
  const starts = [], contains = [];
  for (const it of US_STOCKS) {
    const name = kata(norm(it.name));
    if (it.symbol.toLowerCase().startsWith(n) || name.startsWith(n)) starts.push(it);
    else if (name.includes(n)) contains.push(it);
  }
  return [...starts, ...contains].slice(0, limit);
}
