// 「？」付きのラベルを作る
export function term(key, label) {
  const t = TERMS[key];
  if (!t) return esc(label);
  return `<button type="button" class="term" data-term="${key}">${esc(label ?? t.term)}<span class="q" aria-hidden="true">?</span></button>`;
}

function show(keys, title) {
  const dlg = $('term-dialog');
  $('term-title').textContent = title;
  $('term-body').innerHTML = keys.map((k) => {
    const t = TERMS[k];
    return `<div class="term-item"><h3>${esc(t.term)}</h3><p>${esc(t.easy)}</p><p class="small muted">${esc(t.more)}</p></div>`;
  }).join('');
  if (!dlg.open) dlg.showModal();
  $('term-body').scrollTop = 0;
}

export function initGlossary() {
  document.addEventListener('click', (e) => {
    const b = e.target.closest('.term[data-term]');
    if (!b) return;
    e.preventDefault();
    e.stopPropagation();
    show([b.dataset.term], '用語の説明');
  });
  $('close-term').addEventListener('click', () => $('term-dialog').close());
  $('term-dialog').addEventListener('click', (e) => { if (e.target === $('term-dialog')) $('term-dialog').close(); });
  $('open-glossary').addEventListener('click', () => show(Object.keys(TERMS), '用語集'));
}
